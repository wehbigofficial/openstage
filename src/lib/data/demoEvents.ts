export interface EventItem {
  id: string;
  owner_id?: string;
  title: string;
  artist_name: string;
  venue_name: string;
  address: string;
  city: string;
  country: string;
  lat: number;
  lng: number;
  approximate_location: boolean;
  starts_at: string; // ISO 8601
  timezone: string;
  genre: string;
  event_type: 'concert' | 'club night' | 'festival' | 'party' | 'open mic' | 'other';
  image_url: string;
  description: string;
  ticket_url?: string;
  price_text: string;
  is_free: boolean;
  lineup?: string[];
  links?: {
    spotify?: string;
    instagram?: string;
    website?: string;
  };
  status: 'published' | 'draft' | 'hidden' | 'cancelled';
  is_featured: boolean;
  is_unclaimed?: boolean;
  is_demo: boolean;
  is_emerging?: boolean;
  created_at?: string;
}

// Generate future dates relative to current date so demo events stay active
const getFutureDate = (daysAhead: number, hours: number, minutes = 0): string => {
  const d = new Date();
  d.setDate(d.getDate() + daysAhead);
  d.setHours(hours, minutes, 0, 0);
  return d.toISOString();
};

